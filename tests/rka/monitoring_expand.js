const fs = require('fs');
const vm = require('vm');
const path = require('path');
const template = fs.readFileSync(path.join(__dirname, '../../app/Views/akutansi/monitoring_anggaran.php'), 'utf8');
const script = template.match(/<script>\s*([\s\S]*?)\s*<\/script>/)[1];
const details = { one: { hidden: true }, two: { hidden: true }, popup: { hidden: true, note: 'Catatan yang belum disimpan' } };
const attributes = { 'aria-expanded': 'false', 'aria-controls': 'one two' };
const button = { getAttribute: (key) => attributes[key], setAttribute: (key, value) => { attributes[key] = value; } };
const row = { querySelector: () => button, addEventListener: (_, handler) => { row.click = handler; } };
const popupAttributes = { 'aria-expanded': 'false', 'aria-controls': 'popup' };
const popupButton = { getAttribute: (key) => popupAttributes[key], setAttribute: (key, value) => { popupAttributes[key] = value; } };
const popupRow = { querySelector: () => popupButton, addEventListener: (_, handler) => { popupRow.click = handler; } };
const dialog = { dataset: {}, querySelectorAll: () => [{ addEventListener: (_, handler) => { dialog.closeHandler = handler; } }], showModal: () => { dialog.open = true; }, close: () => { dialog.open = false; } };
const action = { addEventListener: (_, handler) => { action.click = handler; }, closest: () => ({ removeAttribute: () => {} }) };
const exportForm = { addEventListener: (_, handler) => { exportForm.submit = handler; } };
const exportDialog = { querySelectorAll: () => [{ addEventListener: (_, handler) => { exportDialog.closeHandler = handler; } }], querySelector: () => exportForm, showModal: () => { exportDialog.open = true; }, close: () => { exportDialog.open = false; } };
const exportAction = { addEventListener: (_, handler) => { exportAction.click = handler; }, closest: () => ({ removeAttribute: () => {} }) };
vm.runInNewContext(script, { document: { querySelectorAll: () => [row, popupRow], querySelector: (selector) => selector === '[data-monitoring-export-open]' ? exportAction : action, getElementById: (id) => id === 'monitoringEditDialog' ? dialog : id === 'monitoringExportDialog' ? exportDialog : details[id] } });
const labelClick = { target: { closest: () => null } };
row.click(labelClick);
if (attributes['aria-expanded'] !== 'true' || details.one.hidden || details.two.hidden) throw new Error('Failed to expand.');
row.click(labelClick);
if (attributes['aria-expanded'] !== 'false' || !details.one.hidden || !details.two.hidden) throw new Error('Failed to collapse.');
popupRow.click(labelClick);
if (popupAttributes['aria-expanded'] !== 'true' || details.popup.hidden) throw new Error('Popup did not expand.');
popupRow.click({ target: { closest: () => ({}) } });
if (popupAttributes['aria-expanded'] !== 'true' || details.popup.hidden) throw new Error('Editing a group note must not collapse it.');
popupRow.click(labelClick);
if (popupAttributes['aria-expanded'] !== 'false' || !details.popup.hidden || details.popup.note !== 'Catatan yang belum disimpan') throw new Error('Popup collapse must preserve edited notes.');
action.click({ currentTarget: action });
if (!dialog.open) throw new Error('Edit dialog did not open.');
dialog.closeHandler();
if (dialog.open) throw new Error('Edit dialog did not close.');
exportAction.click({ currentTarget: exportAction });
if (!exportDialog.open) throw new Error('Export period dialog did not open.');
exportDialog.closeHandler();
if (exportDialog.open) throw new Error('Export period dialog did not close.');
exportAction.click({ currentTarget: exportAction });
exportForm.submit();
if (exportDialog.open) throw new Error('Export period dialog did not close on submission.');
console.log('Monitoring expand interaction: passed');
